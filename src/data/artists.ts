/**
 * Curated artist roster used to build the track catalogue (scripts/build-catalogue.ts)
 * and to power the Artists filter reel / collection pages.
 *
 * tier: 1 = global megastar, 2 = very famous, 3 = famous, 4 = niche / deep cuts.
 * featured: shown in the in-game Artists reel.
 */
export type ArtistSeed = {
  name: string;
  slug: string;
  tier: 1 | 2 | 3 | 4;
  featured?: boolean;
  /** iTunes store to query first (default "US"). */
  country?: string;
  /** Alternate search term when the display name is ambiguous. */
  term?: string;
};

const a = (
  name: string,
  tier: 1 | 2 | 3 | 4,
  opts: Partial<Omit<ArtistSeed, "name" | "tier">> = {},
): ArtistSeed => ({
  name,
  tier,
  slug:
    opts.slug ??
    name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/&/g, "and")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, ""),
  ...opts,
});

